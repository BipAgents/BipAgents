//! The search's words in fr, en, de, es and nl (plan « Le sommaire » §3.2, brick S3): what goes with the phone's copy
//! (`GET /v1/notebook/index`: `stop`, `neighbours`, `dates`) and what the bridge's own search reads (finder.rs).
//!
//! - **Neighbours**: groups of words that mean the same thing for a search (« toubib », « médecin », « docteur »);
//!   each word of a group has the others as its neighbours (found as themselves only: finder.rs). About 300 words a
//!   language. A group member of several words (« salle de sport ») is one term. Folded (lower case, no accents).
//! - **Date phrases**: « la semaine prochaine », « avant Noël », « next week », « nächste Woche », « la semana que
//!   viene », « volgende week »… → an interval computed on the phone (`DateEnd`: `day`, `week`, `month`, `year`,
//!   `feast`, `weekday`); feasts as rules (a fixed day, or days from Easter), never days: the copy never changes with
//!   the day. A month's name is no phrase: its word finds the dates written with it (« anniversaires en décembre »).
//! - **Stop words**: the lexicon's (`lexicon::STOP`, the answers' and the 1.0 search's, unchanged) and, for this
//!   search only, Dutch's and the words a spoken question carries (« euh », « je dois », « remind me »).
//!
//! Left out on purpose until the blind set (briefs/carnet-blind-set-1122.json, 22/11) has been measured once: the
//! words its README names (« rdv », « proprio », « CAF », « PTO », « ISA », « Bank », « banco », « poen »,
//! « curro », « pasta », « cv », « VvE », « Sinterklaas »…), so that its numbers stay blind.

